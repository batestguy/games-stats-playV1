"""Refresh the local, offline browser copy of the app's draft question bank."""

import json
from pathlib import Path
from shutil import copyfile

from app.game import load_question_bank
from app.hints import reflection_hint


def main():
    preview = Path(__file__).resolve().parent
    assets = preview.parent / "app" / "assets"
    bank = load_question_bank(assets)
    fields = ("id", "concept", "level", "difficulty", "clue_type", "clue", "choices", "answer", "explanation")
    questions = [
        {
            **{key: getattr(item, key) for key in fields},
            "hint": reflection_hint(item),
            **({"math_clue": item.math_clue} if item.math_clue else {}),
            **({"math_choices": item.math_choices} if item.math_choices else {}),
        }
        for item in bank
    ]
    lines = ",\n".join(json.dumps(item, ensure_ascii=False, separators=(",", ":")) for item in questions)
    (preview / "bank.js").write_text(
        "// Generated by python -m preview.sync_bank. Edit app/assets to update.\n"
        f"globalThis.QUIZ_BANK = [\n{lines}\n];\n",
        encoding="utf-8",
        newline="\n",
    )
    author = json.loads((assets / "author.json").read_text(encoding="utf-8"))
    (preview / "author.js").write_text(
        "// Generated by python -m preview.sync_bank from app/assets/author.json.\n"
        f"globalThis.QUIZ_AUTHOR = {json.dumps(author, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
        newline="\n",
    )
    copyfile(assets / author["photo"], preview / author["photo"])


if __name__ == "__main__":
    main()
