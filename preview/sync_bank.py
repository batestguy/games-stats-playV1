"""Refresh the local, offline browser copy of the app's draft question bank."""

from dataclasses import asdict
import json
from pathlib import Path

from app.game import load_question_bank


def main():
    preview = Path(__file__).resolve().parent
    bank = load_question_bank(preview.parent / "app" / "assets")
    fields = ("id", "concept", "level", "difficulty", "clue_type", "clue", "choices", "answer", "explanation")
    questions = [{key: row[key] for key in fields} for row in map(asdict, bank)]
    lines = ",\n".join(json.dumps(item, ensure_ascii=False, separators=(",", ":")) for item in questions)
    (preview / "bank.js").write_text(
        "// Generated by python -m preview.sync_bank. Edit app/assets to update.\n"
        f"globalThis.QUIZ_BANK = [\n{lines}\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
