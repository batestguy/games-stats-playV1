"""Typeset the authored LaTeX for offline use in Kivy and the browser preview."""

from base64 import b64encode
from io import BytesIO
import json
from pathlib import Path
from struct import unpack

from matplotlib import rc_context
from matplotlib.font_manager import FontProperties
from matplotlib.mathtext import math_to_image

from app.equations import choice_parts, equation_parts
from app.game import load_question_bank


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "app" / "assets"
PREVIEW = ROOT / "preview"
SCALE = 2
EQUATION_FONT = FontProperties(size=22)


def render(tex):
    image = BytesIO()
    math_to_image(f"${tex}$", image, prop=EQUATION_FONT, dpi=72 * SCALE, format="png", color="white")
    data = image.getvalue()
    width, height = unpack(">II", data[16:24])
    return {"png": b64encode(data).decode("ascii"), "width": width, "height": height}


def main():
    sources = {}
    for question in load_question_bank(ASSETS):
        displayed = [equation_parts(markup) for markup in (question.math_clue, question.math_explanation) if markup]
        displayed.extend(choice_parts(markup) for markup in question.math_choices.values())
        for parts in displayed:
            if not any(is_math for is_math, _ in parts) or any(
                "$" in part for is_math, part in parts if not is_math
            ):
                raise ValueError(f"Unmatched math delimiters for {question.id}")
            for is_math, part in parts:
                if is_math:
                    sources.setdefault(part, question.id)
    rows = []
    with rc_context({"savefig.transparent": True, "mathtext.fontset": "stix"}):
        for tex, question_id in sorted(sources.items()):
            try:
                rows.append((tex, render(tex)))
            except ValueError as error:
                raise ValueError(f"Cannot typeset the equation in {question_id}: {tex!r}") from error
    data = "{\n" + ",\n".join(
        f"  {json.dumps(tex, ensure_ascii=False)}: {json.dumps(image, separators=(',', ':'))}"
        for tex, image in rows
    ) + "\n}"
    (ASSETS / "equations.json").write_text(data + "\n", encoding="utf-8", newline="\n")
    (PREVIEW / "equations.js").write_text(
        "// Generated by python -m curriculum.render_equations.\n"
        f"globalThis.QUIZ_EQUATIONS = {data};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Rendered {len(rows)} distinct equations.")


if __name__ == "__main__":
    main()
